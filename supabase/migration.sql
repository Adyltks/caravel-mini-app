-- Таблицы Telegram Mini App Caravel.
-- Префикс aduka_, чтобы не пересекаться с другими проектами в той же базе.
-- Выполнить один раз в Supabase: SQL Editor → New query → вставить → Run.

create table if not exists public.aduka_services (
  id text primary key,
  title text not null,
  short text not null default '',
  description text not null default '',
  price integer not null default 0,
  term text not null default '',
  badge text,
  icon text not null default 'catalog',
  featured boolean not null default false,
  includes jsonb not null default '[]'::jsonb,
  steps jsonb not null default '[]'::jsonb,
  sort integer not null default 100,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.aduka_orders (
  id bigint generated by default as identity (start with 1001) primary key,
  created_at timestamptz not null default now(),
  name text not null default '',
  phone text not null,
  username text,
  tg_id bigint,
  services jsonb not null default '[]'::jsonb,
  total integer not null default 0,
  comment text not null default '',
  status text not null default 'new'
);

create table if not exists public.aduka_settings (
  key text primary key,
  value jsonb not null
);

alter table public.aduka_services enable row level security;
alter table public.aduka_orders enable row level security;
alter table public.aduka_settings enable row level security;

-- Публично читаются только активные услуги и настройки.
-- Все записи делает сервер бота сервисным ключом (service_role), он обходит RLS.
drop policy if exists aduka_services_public_read on public.aduka_services;
create policy aduka_services_public_read on public.aduka_services
  for select to anon, authenticated using (active);
drop policy if exists aduka_settings_public_read on public.aduka_settings;
create policy aduka_settings_public_read on public.aduka_settings
  for select to anon, authenticated using (true);

